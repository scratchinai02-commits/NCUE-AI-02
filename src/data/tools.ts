export interface ToolStep {
  title: string;
  prompt: string;
  /** 貼上後應該看到的結果，讓使用者確認可以進下一步 */
  check: string;
}

export interface ToolDef {
  id: ToolId;
  group: ToolGroup;
  /** 對應講座主題，例如 AI Research、AI Lesson */
  theme?: string;
  title: string;
  tagline: string;
  desc: string;
  /** 生成的 App 名稱 */
  appName: string;
  /** 若 App 需要上傳檔案，在第 1 步加上檔案處理規格 */
  upload?: string;
  steps: ToolStep[];
}

